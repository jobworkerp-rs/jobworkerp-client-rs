/// Type alias for the `collect_stream` return type to reduce complexity
pub type CollectStreamFuture = std::pin::Pin<
    Box<dyn std::future::Future<Output = Result<(Vec<u8>, HashMap<String, String>)>> + Send>,
>;

/// Legacy `PluginRunner` trait (origin/main compatible)
///
/// This trait maintains binary compatibility with plugins compiled against origin/main.
/// DO NOT modify this trait definition - it will break existing plugin binaries!
#[allow(clippy::missing_errors_doc)]
pub trait PluginRunner: Send + Sync {
    fn name(&self) -> String;
    fn description(&self) -> String;
    fn load(&mut self, settings: Vec<u8>) -> Result<()>;
    fn run(
        &mut self,
        args: Vec<u8>,
        metadata: HashMap<String, String>,
    ) -> (Result<Vec<u8>>, HashMap<String, String>);
    // run for generating stream
    fn begin_stream(&mut self, arg: Vec<u8>, metadata: HashMap<String, String>) -> Result<()> {
        // default implementation (return empty)
        let (_, _) = (arg, metadata);
        Err(anyhow::anyhow!("not implemented"))
    }
    // receive stream generated by run_stream()
    fn receive_stream(&mut self) -> Result<Option<Vec<u8>>> {
        // default implementation (return empty)
        Err(anyhow::anyhow!("not implemented"))
    }
    fn cancel(&self) -> bool;
    fn is_canceled(&self) -> bool;
    fn runner_settings_proto(&self) -> String;
    fn job_args_proto(&self) -> String;
    fn result_output_proto(&self) -> Option<String>;
    fn output_type(&self) -> crate::jobworkerp::data::StreamingOutputType {
        crate::jobworkerp::data::StreamingOutputType::NonStreaming
    }
    fn settings_schema(&self) -> String {
        let schema = schemars::schema_for!(crate::jobworkerp::data::Empty);
        match serde_json::to_string(&schema) {
            Ok(s) => s,
            Err(e) => {
                tracing::error!("error in settings_schema: {:?}", e);
                String::new()
            }
        }
    }
    fn arguments_schema(&self) -> String {
        let schema = schemars::schema_for!(crate::jobworkerp::data::Empty);
        match serde_json::to_string(&schema) {
            Ok(s) => s,
            Err(e) => {
                tracing::error!("error in arguments_schema: {:?}", e);
                String::new()
            }
        }
    }
    fn output_json_schema(&self) -> Option<String> {
        None
    }
}

/// Multi-method `PluginRunner` trait (new plugins)
///
/// This trait is for new plugins that support multiple methods via `method_proto_map()`.
/// Use this for plugins that need to expose multiple callable methods.
#[allow(clippy::missing_errors_doc)]
pub trait MultiMethodPluginRunner: Send + Sync {
    fn name(&self) -> String;
    fn description(&self) -> String;
    fn load(&mut self, settings: Vec<u8>) -> Result<()>;
    /// Execute with optional method selection
    ///
    /// # Arguments
    /// * `args` - Protobuf binary arguments
    /// * `metadata` - Job metadata
    /// * `using` - Optional method name for multi-method plugins
    fn run(
        &mut self,
        args: Vec<u8>,
        metadata: HashMap<String, String>,
        using: Option<&str>,
    ) -> (Result<Vec<u8>>, HashMap<String, String>);
    /// Begin streaming execution with optional method selection
    ///
    /// # Arguments
    /// * `arg` - Protobuf binary arguments
    /// * `metadata` - Job metadata
    /// * `using` - Optional method name for multi-method plugins
    fn begin_stream(
        &mut self,
        arg: Vec<u8>,
        metadata: HashMap<String, String>,
        using: Option<&str>,
    ) -> Result<()> {
        // default implementation (return empty)
        let (_, _, _) = (arg, metadata, using);
        Err(anyhow::anyhow!("not implemented"))
    }
    /// Receive the next chunk from the stream started by `begin_stream()`.
    ///
    /// Returns `Ok(Some(data))` for each chunk, `Ok(None)` when the stream ends.
    ///
    /// **Blocking constraint**: This method runs inside `spawn_blocking`, so it MAY block
    /// the calling thread. However, it MUST NOT block indefinitely — it should return
    /// promptly (within seconds) when no more data is available or when the plugin is
    /// cancelled. See `PluginRunner::receive_stream()` for full details.
    fn receive_stream(&mut self) -> Result<Option<Vec<u8>>> {
        // default implementation (return empty)
        Err(anyhow::anyhow!("not implemented"))
    }
    /// Cancel the running task.
    /// Unlike `PluginRunner` (legacy), this takes `&mut self` for simpler plugin implementation.
    fn cancel(&mut self) -> bool;
    fn is_canceled(&self) -> bool;
    fn runner_settings_proto(&self) -> String;

    /// Key: method name, Value: `MethodSchema` (input and output schemas)
    fn method_proto_map(&self) -> HashMap<String, crate::jobworkerp::data::MethodSchema>;

    /// Optional: Provide custom JSON schemas
    /// If None, automatic conversion from `method_proto_map()` will be used
    fn method_json_schema_map(
        &self,
    ) -> Option<HashMap<String, crate::jobworkerp::data::MethodJsonSchema>> {
        None
    }

    fn settings_schema(&self) -> String {
        super::schema_to_json_string!(crate::jobworkerp::data::Empty, "settings_schema")
    }

    /// Whether this plugin supports client streaming input for the given method
    fn supports_client_stream(&self, _using: Option<&str>) -> bool {
        false
    }

    /// Proto definition for client streaming data of the given method
    fn client_stream_data_proto(&self, _using: Option<&str>) -> Option<String> {
        None
    }

    /// Set up a client stream channel for receiving raw bytes during streaming execution.
    /// The wrapper layer bridges this to `FeedData` by spawning an adapter task.
    fn setup_client_stream_channel(
        &mut self,
        _using: Option<&str>,
    ) -> Option<tokio::sync::mpsc::Sender<Vec<u8>>> {
        None
    }

    /// Collect streaming output into a single result
    ///
    /// Default implementation: keeps only the last data chunk
    /// (protobuf binary concatenation produces invalid data), and fails when the End trailer
    /// reports a stream failure
    /// Plugins should override this for custom collection logic (e.g., merging proto messages)
    fn collect_stream(
        &self,
        stream: futures::stream::BoxStream<'static, crate::jobworkerp::data::ResultOutputItem>,
        _using: Option<&str>,
    ) -> CollectStreamFuture {
        use crate::jobworkerp::data::result_output_item;
        use futures::StreamExt;

        Box::pin(async move {
            let mut last_data: Option<Vec<u8>> = None;
            let mut metadata = HashMap::new();
            let mut stream = stream;
            // Separate variable for FinalCollected to avoid being overwritten by late Data chunks
            let mut final_collected: Option<Vec<u8>> = None;

            while let Some(item) = stream.next().await {
                match item.item {
                    Some(result_output_item::Item::Data(data)) => {
                        last_data = Some(data);
                    }
                    Some(result_output_item::Item::FinalCollected(data)) => {
                        final_collected = Some(data);
                    }
                    Some(result_output_item::Item::End(trailer)) => {
                        // A failed End must not be collected as a (partial) success.
                        if let Some(error) =
                            crate::stream_error::stream_error_from_trailer(&trailer)
                        {
                            return Err(crate::stream_error::stream_failure_error(&error));
                        }
                        metadata = trailer.metadata;
                        break;
                    }
                    None => {}
                }
            }
            Ok((final_collected.or(last_data).unwrap_or_default(), metadata))
        })
    }
}

/// Macro to convert a Rust type to a JSON schema string
#[macro_export]
macro_rules! schema_to_json_string {
    ($type:ty, $method_name:expr_2021) => {{
        let schema = schemars::schema_for!($type);
        match serde_json::to_string(&schema) {
            Ok(s) => s,
            Err(e) => {
                tracing::error!("error in {}: {:?}", $method_name, e);
                String::new()
            }
        }
    }};
}

/// Macro to convert a Rust type to an Option<String> JSON schema
#[macro_export]
macro_rules! schema_to_json_string_option {
    ($type:ty, $method_name:expr_2021) => {{
        let schema = schemars::schema_for!($type);
        match serde_json::to_string(&schema) {
            Ok(s) => Some(s),
            Err(e) => {
                tracing::error!("error in {}: {:?}", $method_name, e);
                None
            }
        }
    }};
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::jobworkerp::data::{
        ResultOutputItem, StreamError, StreamErrorCode, Trailer, result_output_item,
    };
    use crate::stream_error::{COMMON_STREAM_ERROR_KEY, PLUGIN_RUN_STREAM_ERROR_KEY};
    use futures::StreamExt;

    struct DefaultCollect;

    impl MultiMethodPluginRunner for DefaultCollect {
        fn name(&self) -> String {
            "DefaultCollect".to_string()
        }
        fn description(&self) -> String {
            String::new()
        }
        fn load(&mut self, _settings: Vec<u8>) -> Result<()> {
            Ok(())
        }
        fn run(
            &mut self,
            _args: Vec<u8>,
            metadata: HashMap<String, String>,
            _using: Option<&str>,
        ) -> (Result<Vec<u8>>, HashMap<String, String>) {
            (Ok(Vec::new()), metadata)
        }
        fn cancel(&mut self) -> bool {
            false
        }
        fn is_canceled(&self) -> bool {
            false
        }
        fn runner_settings_proto(&self) -> String {
            String::new()
        }
        fn method_proto_map(&self) -> HashMap<String, crate::jobworkerp::data::MethodSchema> {
            HashMap::new()
        }
    }

    async fn collect(end: Trailer) -> Result<(Vec<u8>, HashMap<String, String>)> {
        let items = [
            ResultOutputItem {
                item: Some(result_output_item::Item::Data(b"first".to_vec())),
            },
            ResultOutputItem {
                item: Some(result_output_item::Item::Data(b"last".to_vec())),
            },
            ResultOutputItem {
                item: Some(result_output_item::Item::End(end)),
            },
        ];
        DefaultCollect
            .collect_stream(futures::stream::iter(items).boxed(), None)
            .await
    }

    #[tokio::test]
    async fn default_collect_stream_keeps_the_last_chunk_on_a_clean_end() {
        let (output, metadata) = collect(Trailer {
            metadata: HashMap::from([("k".to_string(), "v".to_string())]),
            ..Default::default()
        })
        .await
        .expect("clean end");
        assert_eq!(output, b"last");
        assert_eq!(
            metadata,
            HashMap::from([("k".to_string(), "v".to_string())])
        );
    }

    #[tokio::test]
    async fn default_collect_stream_rejects_a_typed_failed_end() {
        let error = collect(Trailer {
            error: Some(StreamError {
                code: StreamErrorCode::ExecutionFailed as i32,
                message: "boom".to_string(),
                origin: "PLUGIN_X".to_string(),
            }),
            ..Default::default()
        })
        .await
        .expect_err("failed end");
        assert!(
            error
                .to_string()
                .contains("PLUGIN_X EXECUTION_FAILED: boom"),
            "{error:#}"
        );
    }

    #[tokio::test]
    async fn default_collect_stream_rejects_legacy_failure_keys() {
        for key in [PLUGIN_RUN_STREAM_ERROR_KEY, COMMON_STREAM_ERROR_KEY] {
            let result = collect(Trailer {
                metadata: HashMap::from([(key.to_string(), "failed".to_string())]),
                ..Default::default()
            })
            .await;
            assert!(result.is_err(), "{key} must fail the collect");
        }
    }
}
